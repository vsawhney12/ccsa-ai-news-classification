def main():

    parser = argparse.ArgumentParser(
        description=__doc__
    )

    parser.add_argument(
        "--consensus",
        type=Path,
        default=(
            CONSENSUS_DIR
            / "expanded_consensus_reference.csv"
        ),
    )

    parser.add_argument(
        "--qwen",
        type=Path,
        default=(
            DATA_DIR
            / "ArticlesV2_Blind_review_qwen.csv"
        ),
    )

    parser.add_argument(
        "--llama",
        type=Path,
        default=(
            DATA_DIR
            / "ArticlesV2_Blind_review_llama.csv"
        ),
    )

    parser.add_argument(
        "--mistral",
        type=Path,
        default=(
            DATA_DIR
            / "ArticlesV2_Blind_review_mistral.csv"
        ),
    )

    parser.add_argument(
        "--output-dir",
        type=Path,
        default=DEFAULT_OUTPUT_DIR,
    )

    args = parser.parse_args()

    try:

        # --------------------------------------------------
        # READ REFERENCE DATA
        # --------------------------------------------------

        consensus = read_consensus(
            args.consensus
        )

        validate_consensus(
            consensus
        )

        # --------------------------------------------------
        # READ MODEL PREDICTIONS
        # --------------------------------------------------

        predictions = {
            "Qwen": read_predictions(
                args.qwen
            ),
            "Llama": read_predictions(
                args.llama
            ),
            "Mistral": read_predictions(
                args.mistral
            ),
        }

        validate_predictions(
            consensus,
            predictions,
        )

        # --------------------------------------------------
        # BUILD ARTICLE AUDIT
        # --------------------------------------------------

        audit = build_article_audit(
            consensus,
            predictions,
        )

        # --------------------------------------------------
        # COMPARE MODELS
        # --------------------------------------------------

        (
            model_results,
            confidence_results,
            pairwise_results,
            class_results,
            coverage_results,
        ) = compare_models(
            audit
        )

        

        # --------------------------------------------------
        # SAVE RESULTS
        # --------------------------------------------------

        save_results(
            args.output_dir,
            model_results,
            confidence_results,
            pairwise_results,
            class_results,
            coverage_results,
            audit,
        )

        # --------------------------------------------------
        # PRINT SUMMARY
        # --------------------------------------------------

        print("\nMODEL COMPARISON COMPLETE")
        print("-" * 50)

        print(
            f"Consensus articles: {len(consensus)}"
        )

        for row in coverage_results:

            print(
                f"{row['Reference set']}: "
                f"{row['Shared N']} / "
                f"{row['Reference N']} evaluable"
            )

        print("\nMODEL ACCURACY")

        for row in model_results:

            if row["Reference set"] in (
                "Original consensus",
                "Expanded consensus",
            ):

                print(
                    f"{row['Reference set']} | "
                    f"{row['Model']}: "
                    f"{row['Accuracy']:.3f} "
                    f"(95% CI "
                    f"{row['Accuracy 95% CI lower']:.3f}-"
                    f"{row['Accuracy 95% CI upper']:.3f})"
                )

        print(
            f"\nResults saved to: {args.output_dir}"
        )

    except (
        ValueError,
        OSError,
        csv.Error,
    ) as error:

        parser.exit(
            1,
            f"Error: {error}\n",
        )


if __name__ == "__main__":
    main()