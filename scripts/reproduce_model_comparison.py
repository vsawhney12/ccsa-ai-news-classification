# READ MODEL PREDICTIONS
# ==========================================================

def read_predictions(path):
    """Read saved model classifications."""

    records = {}

    with path.open(
        newline="",
        encoding="utf-8-sig",
    ) as file:

        reader = csv.DictReader(file)

        required = {
            "review_id",
            "reviewed_primary_category",
        }

        if (
            reader.fieldnames is None
            or not required <= set(reader.fieldnames)
        ):
            raise ValueError(
                f"{path}: required prediction columns missing."
            )

        for row in reader:

            review_id = normalize_id(
                row["review_id"]
            )

            prediction = normalize_label(
                row["reviewed_primary_category"]
            )

            if prediction not in (
                *LABELS,
                "",
                "N/A",
                "Unknown",
            ):
                raise ValueError(
                    f"{path}: unexpected prediction "
                    f"{prediction!r}, ID {review_id}"
                )

            if review_id in records:
                raise ValueError(
                    f"{path}: duplicate ID {review_id}"
                )

            records[review_id] = prediction

    return records


